		    <h2><b>Abstract: </b> </h2>
			<p>In most of the major financial centers in the world, financial regulators oversee and regulate the activities of financial institutions to enable integrity and transparency in the financial market, to protect customers, investors, the economy, and society, and to prevent financial crime, market manipulation, ethical threats, and systemic risk. Regulation technology, or RegTech, is about making use of technology to drive automation and overcome challenges in the management of regulatory processes while Supervisory technology, or SupTech, involves using technology by regulatory authorities to monitor, supervise and enforce compliance with financial regulations. In this talk, we will discuss how to enrich RegTech and SupTech, and some other related domains, with language AI technologies, and explore various applications of speech recognition, speaker verification, natural language processing, large language models, and more. We will also illustrate some real-life examples in Hong Kong and some other financial centers.
			</p>
			
