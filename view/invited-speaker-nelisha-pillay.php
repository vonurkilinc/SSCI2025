				<h2><b>Biography:</b></h2>
				Nelishia Pillay is a Professor at the University of Pretoria, South Africa. She holds the Multichoice Joint-Chair in Machine Learning and SARChI Chair in Artificial Intelligence for Sustainable Development. She is involved in various activities of the IEEE Computational Intelligence Society. She is chair of the IEEE CIS Mentoring Program subcommittee, IEEE subcommittee for Diversity, Equity and Inclusion and the IEEE CIS Award for Outstanding PhD Dissertation subcommittee, Technical Co-Chair for Evolutionary Computation for IEEE WCCI 2024 and CEC Conference Co-Chair for IEEE WCCI 2026. She has served as associate editor of various international journals in her field and is currently associate editor for IEEE Transactions on Emerging Topics in Computational Intelligence and ACM Transactions on Evolutionary Learning and Optimization. Her research areas include hyper-heuristics, automated design of machine learning and search techniques, transfer learning, combinatorial optimization, genetic programming, genetic algorithms and machine learning and optimization for sustainable development. These are the focus areas of the NICOG (Nature-Inspired Computing Optimization) research group which she has established.		
