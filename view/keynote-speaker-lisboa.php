		    <h2><b>Abstract: </b> </h2>
			<p>The talk will focus on practical aspects of the development of real-world clinical applications. It will start with an overview of currently approved machine learning based medical systems and highlight potential limitations for multicentre use. These reflect the importance of looking beyond the performance of the model, to avoid spurious effects and bias. It will be shown how flexible models of tabular data can be expressed as additive models, forming a bridge between machine learning and statistics. Large-scale data on heart transplants will be used to show how self-explaining models can buck the performance-transparency trade-off by matching the predictive power of deep learning but with full transparency. This leads to key ethical considerations relevant to the development of practical clinical systems involving flexible models.	
			</p>

				<p>
				<h2><b>Biography:</b></h2>
				Paulo Lisboa is Emeritus Professor at Liverpool John Moores University. He is a long-time advocate of interpretable machine learning, with over 250 peer reviewed publications and consultancies on real-word applications.  He is former chair of the Expert Advisory Group for Societal Challenge 1: Health, Demographic Change and Wellbeing in Horizon 2020, the world's largest coordinated research programme in health. Previously, he chaired the Healthcare Technologies Professional Network of the Institution of Engineering and Technology, and task forces on Medical Data Analysis and Explainable Machine Learning in the IEEE Computational Intelligence Society.</p>
