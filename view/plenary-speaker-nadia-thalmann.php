				<h2><b>Biography:</b></h2>
				
				 <p>Professor Thalmann has established <strong>MIRALab at the  University of Geneva</strong> in Switzerland, a ground-breaking interdisciplinary  multimedia research institute. She participated in more than 50 European  research projects, helping <strong>MIRALab</strong> to develop revolutionising <strong>interdisciplinary  research</strong> in computer graphics, computer animation, and virtual worlds and  producing impactful work that synergises art, fashion, computer graphics. Her  work is regularly displayed at <strong>museums, galleries and fashion shows</strong>. </p>
