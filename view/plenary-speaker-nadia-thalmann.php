		    <h2><b>Abstract: </b> </h2>
			<p>  In this talk, we like to present our research on humanoid robots from 2008 to today. We started with EVA, a humanoid head, capable of interacting and showing emotions.  We have performed very early research on Eva on modelling speech and facial expressions.  Eva was  playing on a theatre stage in Zurich in 2010.  In NTU, Singapore, Professor Thalmann has  worked since 2013 on the humanoid Nadine social robot to model it behaviour as a social companion.  This research includes social global awareness, object and actions recognition, gestures modelling including hands, and believable speech dialog interaction. Since 2021, with the venue of LLMs, a new platform has been implemented extending LLMs  models with short and long term memory and Rags.  We will demonstrate Nadine in action  and what social robots can do today and tomorrow.	            
			</p>
