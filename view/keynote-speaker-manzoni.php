		    <h2><b>Abstract: </b> </h2>
			<p>In 1954 the Norwegian-Italian  scientist Nils Aall Barricelli published one of the first works on artificial  life, titled &quot;Esempi numerici di processi di evoluzione&quot; (translated  in 1957 as &quot;Symbiogenetic evolution processes realized by artificial  methods&quot;).<br />
His work represents a pioneering  example of artificial life and evolutionary algorithms, conducted on some of  the earliest electronic computers.<br />
Over 70 years since these initial  publications, this talk will revisit Barricelli&rsquo;s discoveries, his aspirations  for future advancements, and whether these hopes have been realized through  subsequent decades of research. After such a span of time, does Barricelli's  work still offer inspiration today?
</p>
			
			<p>
			<h2><b>Biography:</b></h2>
Luca Manzoni is an associate  professor of computer science at the University of Trieste and head of the  Natural Computing Laboratory (NaCL). He received his PhD in computer science  from the University of Milano-Bicocca in 2013, where he also obtained his  master in 2009. During his career he was a visiting students or a postdoc in  Lisbon, Birmingham, Nice, and Osaka.</p>
			 <p>He published more than 150  scientific papers in international conferences and journals. In 2022 he  received the SIGEVO impact award, recognizing seminal papers in evolutionary  computations published 10 years before. He is currently involved as PI or unit  leader in multiple national and international projects.</p>
			 <p>His interest are in the fields of  evolutionary computation, natural computing models, and applications of AI  techniques to the natural sciences.&nbsp;
