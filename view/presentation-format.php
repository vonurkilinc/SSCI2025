		   <h4 class="content-headline">Presentation Format</h4>
			<p>
		The presentation format is as follows:
			<ul>
			   <li><b>Full papers:</b> IEEE SSCI 2025 will be using a new presentation format for full papers. Each full paper will be presented by a short oral presentation followed by a poster presentation (for exceptions, see the paragraph below the bullet points). The new presentation format aims at increasing interactions at the conference. <b>Oral presentations should be up to 7 min (strict)</b>. There will be a short time for questions after the presentation while switching presenters. More discussions will then be invited to happen at the poster session.</li>
				<li><b>Short papers:</b> poster presentation.</li>
				<li><b>Late breaking papers:</b> poster presentation.</li>
				<li><b>Abstract (poster-only):</b> poster presentation. </li>
				<li><b>Journal to conference papers:</b> short oral presentation followed by a poster presentation. <b>The length of the oral presentation is the same as for the full papers above.</b></li>			
			</ul>
			
			<h4 class="content-headline">IEEE SSCI 2025 is an in-person conference</h4>
			IEEE has a policy for 'no-show' where the presenter of an oral or poster presentation does not present their work. The 'no-show' papers will not be included on IEEE Xplore. Please note that, for full paper presentations, presence is required both at the oral and at the subsequent poster presentation of the paper to avoid a 'no-show'. For short papers and Late Breaking Papers, presence is required at the poster presentation. However, if unexpected travel disruptions arise, please contact our Program Chairs ahead of your scheduled talk, for help and support.
			</p>
