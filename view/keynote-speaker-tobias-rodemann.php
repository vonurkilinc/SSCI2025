		    <h2><b>Abstract: </b> </h2>
			<p>Smart management of energy flows in  buildings in combination with renewable energy sources and EV charging can not  only reduce energy consumption and CO2 emissions, but also provide a rich set  of challenges for Computational Intelligence and data science methods in  general.
			</p>
			<p>
			At our R&amp;D campus a testbed, called Smart Company, for research on energy  management, data monitoring and new energy-related businesses was built,  extending the facility by Photo-Voltaic (PV) systems, charging stations, 2nd  life stationary batteries, H2 electrolyzer, and other elements. More than 100  sensors were installed that measure energy flows in the building. The  measurement data was used to identify savings potentials, develop novel anomaly  detection methods, and fine tune a digital twin of the building. Parts of this  dataset will be made available to the public and I will explain the substantial  challenges in checking and cleaning the data.			
			</p>
			<p>			
			  We have also developed new concepts for  energy management, including a smart charging manager, that is now in operation  for several years and uses a Model Predictive Control approach.			          </p>
			  
			  <p>
			Many-objective optimization methods were used to  identify the optimal sizing of different modules (for example the peak power of  the PV system). I will report on several challenges we encountered and new  research directions, including the topics of fairness and trust.			</p>
			<p><b>Keywords:</b> Energy Management System, Smart Charging, Data Monitoring, Anomaly detection, Model Predictive Control, Business Case analysis </p>

