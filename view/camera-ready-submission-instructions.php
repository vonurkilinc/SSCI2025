		   <h4 class="content-headline">Instructions for submitting your camera-ready paper:</h4>
			<p>
				<p>
	  <h2><b>Step 1: Check your paper is compliant</b>   </h2>
	 <b> Step 1.a:</b> All camera-ready papers must follow the <a href="https://www.ieee.org/conferences/publishing/templates.html" target="_blank"> IEEE conference proceedings template</a>  with body text in 10pt type. Please adhere to the page limitations. For full papers, the limit is 6 pages, plus 1 page for references. A maximum of two extra content pages per full paper is allowed (i.e. up to 8 pages plus 1 page for references), at an additional charge per extra page as specified on the registration page.  For short papers, the limit is 4 pages, plus 1 page for references. 
</p>

<p>

<b>IMPORTANT:</b> Open Science for Full and Short Papers
We encourage all authors to make their data/code available upon acceptance of full and short papers to increase reproducibility and replicability. Please add a note in the last paragraph of the introduction of your submitted paper either stating that you will make your data/code available upon acceptance, or with a justification on why you cannot make your data/code available. Please replace this note by a link to the data/code in your camera-ready paper if you are sharing. You may use any online repository that you wish for this purpose. We suggest Zenodo as it produces a permanent link with a DOI.
</p>

<p>
<b>Step 1.b:</b> IEEE Xplore-compatible PDF file: Your finished paper must be uploaded to <a href="https://ieee-pdf-express.org" target="_blank"> PDF eXpress</a> using the conference ID #####X (see camera-ready submission link for your symposia for exact number) to generate an IEEE Xplore-compatible pdf file before camera-ready submission.
	  
	  </p>
	  
	  <p>
	  <h2><b>Step 2: Upload Camera-Ready Paper</b></h2>
	  
	  Follow the instructions at this link to upload your camera-ready paper: <a href="https://cmt3.research.microsoft.com/docs/help/author/camera-ready-submission.html" target="_blank">Link</a>

Please submit the camera-ready version of your accepted paper <b>no later than 11.59PM, December 22 2024.</b>

	  
	  </p>
	  
	  <p>
	  <h2><b>Step 3: Copyright Form</b></h2>
	  
	  A copyright form is also needed for each accepted paper. Please follow the link in the submission system to complete the electronic copyright form. 
By clicking on the 'Submit IEEE copyright form' link in the Author Console, authors will be redirected to the IEEE eCF site to submit the copyright form. After filling out the IEEE copyright form on eCF site, Authors need to download the form and upload it into CMT. 
For more details, <a href="https://cmt3.research.microsoft.com/docs/help/author/camera-ready-submission.html#ieee-copyright" target="_blank">click here.</a>
</p>

<p>
<b>IMPORTANT:</b> Please ensure that your paper title is current and that the author names and affiliation details are correctly recorded in the CMT system prior to completing the IEEE electronic copyright form. You will not be able to redo the form once it is submitted.
</p>

