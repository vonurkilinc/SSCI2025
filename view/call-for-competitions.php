			<h2><b>Competition Guidelines</b></h2>
			 <ul>
				<li>Competitions require participants to solve CIS-related tasks using software. </li>
				<li>The participants must submit a description of their method for solving the task, initial results, and source codes to the related competition organizers. </li>
				<li>Accepted participants will have to run and demonstrate the software at the conference, in order to be considered an eligible entry. </li>
				<li>The competition organizers will evaluate and rank the submission according to the evaluation criteria submitted with the competition proposal and approved by the SSCI-2025.  </li>
				<li>The GC(s)/PC(s)/SC(s) will evaluate the ranking and accept/reject for demonstration during the SSCI-2025.  </li>
				<li>During the demonstration, the methods and solutions will be evaluated by multiple juries. 
				   <ol>
				      <li>The competition organizers are responsible for selecting the jury panel.
						  <ul>
							<li>To serve as a jury, s/he should have a similar experience/background to an SSCI-2025 reviewer</li>
							<li>The SC (s) must approve the list of juries before the competition during SSCI-2025. </li>
						  </ul>
					  </li>
					  <li> After the demonstrations conclude, the jury announces the competition winner.
						  <ul>
								 <li>The juries will evaluate and rank the demonstrations based on the weights(points) already assigned by the competition organizers and the total weight(points) provided by each jury. </li>
								<li>In the event of equal ranking, the total points from each jury will decide the winner. If still tied, the competition organizer(s) and juries will reach a consensus. </li>
								<li>If still tied, the Symposium Chair(s) will decide the winner based on consensus and current rankings. </li>
						   </ul>
					  </li>
				    </ol>
				  </li>
