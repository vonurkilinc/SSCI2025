		    <h2><b>Abstract: </b> </h2>
			<p>I will explore key obstacles to deploying AI and other technological innovations in healthcare. These challenges include safeguarding data privacy, integrating these technologies seamlessly with clinical workflows, and addressing complex regulatory requirements. I will also discuss the critical need for developing trustworthy, explainable AI models to build confidence among healthcare providers and patients. By showcasing examples from various research projects, I aim to demonstrate how overcoming these barriers can significantly enhance patient care, drive medical research, and ultimately transform healthcare delivery systems.
			</p>
			
			<p>
			<h2><b>Biography:</b></h2>
			Dr. Maria F. Cabrera-Umpierrez holds a PhD in Telecommunications Engineering from Universidad Politecnica de Madrid and is currently a Professor of Biomedical Engineering in the Department of Photonic Technology and Bioengineering at the same university. She serves as the Innovation Director for the Life Supporting Technologies Research Group (LifeSTech), Secretary of the ACTIVAGE.ORG Association, and Treasurer of the International Federation of Medical and Biological Engineering (IFMBE). She is national expert for the European ACCESSIBLE EU resource centre on accessibility. Dr. Cabrera-Umpierrez works as a coordinator and PI on competitive research projects funded by both the European Union and Spanish institutions. Her expertise spans a wide range of applications in the field of Information and Communication Technologies (ICT), applied to sectors such as health, social inclusion, and cultural heritage. This includes the personalization of services, human-machine interaction, interaction design, mobility and accessibility. Dr. Cabrera-Umpierrez has authored more than 100 scientific articles published in national and international journals. </p>	
