		   <h4 class="content-headline">Things to do in Trondheim in March</h4>
			<p>
		Although Trondheim is still in winter in March, a walk along Nidelva or along the promenade from the conference venue to Ila or along Ladestien (pathway along the fjord), o?er great scenic views. The downtown area is so small that many attractions and activities are also within walking distance from the conference venue.
			</p>
				<p>
				 <h2><b>Climate and daylight</b> </h2>
				 March is reputed to be the best time to visit Norway with the days getting longer and super ski conditions. When snow is in abundance in the hills and often also in the city, the light in Trondheim is amazing. The weather is usually snowy or sunny blue skies with the average temperature for March +5 &deg; C to -2 &deg;C  so winter woolies are needed for those used to warmer climates. "There is no bad weather, only bad clothes". The fun doesn't need to stop if one is wearing the appropriate clothes! Although Norway is known for little daylight in winter, during the conference days in March, you can expect over 13,5 hours of daylight

				</p>
				
				<p>
				<h2><b>Outdoors</b> </h2>
				Outdoor sports play an important role in the lives of locals in Trondheim. The woods surrounding Trondheim provide a vast maze of tracks for cross country skiing, including floodlit tracks (until 11pm). Skiing/walking in the floodlit tracks with new snow hanging on the trees is quite magical. Ski equipment can be hired, if needed and the ski areas can be reached by bus or tram.
				</p>
		<p>
		For downhill skiing, there is <a href="https://vassfjellet.no/" target="_blank"> Vassfjellet </a>(a short bus tour from downtown), <a href="https://www.facebook.com/merakeralpinsenter/" target="_blank">Mer&aring;ker Skisenter </a> (75 min with bus, north east), <a href="https://www.oppdalskisenter.no/winter" target="_blank"> Oppdal</a> (120 min with bus, south) or even <a href="https://www.skistar.com/en/ski-destinations/are/winter-in-are/" target="_blank">&Aring;re, Sweden's biggest ski centre </a> with 52 slopes (2 and 1/2 hours, by car or train, north east). Note that delegates can even take the <a href="https://vassfjellet.no/en/take-the-bus-to-vassfjellet/" target="_blank">local bus to Vassfjellet</a> for evening downhill skiing and dinner in the cafe there, after a full day at the conference.
		</p>
		
		<p>
		<img src="assets/images/visit-trondheim-skiing.png" class="img-fluid" alt="" data-aos="zoom-in">
		
		To explore the nature beyond Trondheim and enjoy cross-country skiing or head to the islands (with less snow) to enjoy hiking/fishing etc, it is possible to rent cabins. However, please remember to have suitable clothing and equipment. For more information please refer to: <a href="https://ut.no/" target="_blank">UT - only Norwegian </a>, <a href="https://www.dnt.no/english" target="_blank">The Norwegian Trekking Association</a>, <a href="https://visittrondheim.no/en/activities-attractions/outdoor-adventures/" target="_blank"> Outdoor adventures</a> and <a href="https://www.trondheim.no/en/hiking-and-walks/" target="_blank"> hiking and walks </a>.
		</p>
		
		<p>
			<h2><b>Indoors</b> </h2>
			
			For indoor fun, <a href="https://www.pirbadet.no/home" target="_blank">Pirbadet</a> - situated in the transition between sea and shore - is Norway's biggest waterpark and is placed on the waterfront with the city's best view, in fact in the neighboring building to the venue.				
		</p>
		<p>
		There are several small and big gyms all around the town.
		</p>
		
		<p>
		For climbing enthusiasts, outdoor climbing in winter in Trondheim is not possible but Trondheim has several indoor climbing halls. For more information please check <a href="https://ute.no" target="_blank"> UTE - in Norwegian only - </a> and  <a href="https://gripklatring.no/" target="_blank">Grip Klatring (in Norwegian only).</a>
		</p>
		
		<p>
			<h2><b>Cultural Attractions</b> </h2>
			Trondheim has several indoor and outdoor cultural attractions, most of them in the walking distance from the venue.
		
			
			<br /><br />
			<a href="https://visittrondheim.no/en/activities-attractions/museums/trondheim-kunstmuseum/" target="_blank">Trondheim art museum </a>, historical <a href="https://visittrondheim.no/en/activities-attractions/sightseeing/sverresborg-trondelag-folk-museum/" target="_blank">Sverresborg museum</a> with both indoor and outdoor sections, <a href="https://visittrondheim.no/en/activities-attractions/sightseeing/kristiansten-fortress/" target="_blank">Kristiansten fortress</a>, world's most northernmost cathedral <a href="https://visittrondheim.no/en/activities-attractions/sightseeing/nidaros-cathedral/" target="_blank">Nidaros cathedral</a>, 300 years old <a href="https://visittrondheim.no/en/activities-attractions/sightseeing/old-town-bridge/" target="_blank">Old Town Bridge</a>, historical wooden houses in Bakklandet and royal residence <a href="https://en.wikipedia.org/wiki/Stiftsg%C3%A5rden" target="_blank">Stiftsg&aring;rden</a> are some of the attractions that we recommend!
		</p>
		
