		    <h2><b>Abstract: </b> </h2>
			<p>Precise needle insertion is a cornerstone of robotic surgery, particularly for minimally invasive procedures that demand exceptional accuracy, control, and adaptability within complex anatomical environments. Vision-guided robotic manipulation offers a promising solution by integrating Computer Vision, Artificial Intelligence, and multimodal sensing to achieve precise needle targeting, real-time feedback, and adaptive control. This talk will delve into recent advancements in robotic needle insertion systems, with a focus on how these technologies enable ultrasound-guided precise needle injection systems targeting for challenging procedures, including peripheral and cardiac intravenous access, and pleural effusion treatment. We will present the latest results and innovations that are enhancing precision and autonomy in needle injection applications, ultimately advancing the capabilities of robotic-assisted interventions.
			</p>
			
