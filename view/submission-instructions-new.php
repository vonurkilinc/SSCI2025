		   <h4 class="content-headline">Submission Instructions</h4>
			<p>
		  <h2><b>Double-Anonymous 1-Round Review Process</b>   </h2>
		The review process for IEEE SSCI 2025 will be double-anonymous, i.e. reviewers will not know the authors' identity (and vice-versa). Authors should ensure their anonymity in the submitted papers. In brief:
				 <ul>
				 	<li> authors' names should not be included in the submitted pdf;</li>
					<li>please refer to your prior work in the third person wherever possible;</li>
					<li>a reviewer may be able to deduce the authors' identities by using external resources, such as technical reports published on the web. The availability of information on the web that may allow reviewers to infer the authors' identities does <b>not</b> constitute a breach of the double-anonymous submission policy.</li>
					<li>Note that anonymizing your paper is mandatory, and papers that explicitly or implicitly reveal the authors' identities may be rejected.</li>
				 </ul>
				 </p>
				 
				 <p>				
			All submissions will have either an accept or reject decision, except for full papers. Full papers have three possible decisions: accept, accept as short, or reject. If the full paper is accepted as short, authors are invited to submit a camera-ready with the same format as the short papers for inclusion in the symposia companion proceedings.
				 </p>
				 <p>
			Decisions on submissions will be based on one round of reviews, i.e., there will be no response period or second round of reviews.
			</p>
			
			<p>
		  <h2><b>Paper Submission Rules and Guidelines</b>   </h2>
			 <ul>
			 	<li>Each paper should not reveal author's identities (double-anonymous review process). See instructions above.</li>
