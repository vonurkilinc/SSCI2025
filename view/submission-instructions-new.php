				<li>For a paper to be included in the symposium program, in the proceedings and in IEEEXplore, final accepted papers must be submitted by the camera-ready deadline, the corresponding registration fees must be paid by the early registration deadline, and the paper must presented by at least one author at the required time slots at the conference. For information on the rules for author registration (e.g., how many papers a single author registration can cover, or the type of required registration), please refer to the <a href="<?php echo "?ui=registration"; ?>">registration</a> page.  For more information on the presentation format, please refer to this <a href="<?php echo "?ui=presentation-format"; ?>">link</a>. </li>
		  </ul>
			</p>
			
			<p>
		  <h2><b>Page Limitation and Submission Format </b> </h2>
			 All papers must be submitted using the <a href="https://www.ieee.org/conferences/publishing/templates.html" target="_blank">IEEE conference proceedings template </a> with body text in 10pt type. LaTeX users must use \documentclass[10pt,conference]{IEEEtran}. 
			</p>
			<p>
			The page limitations are as follows:
			<ul>
				<li><b>Full papers:</b> papers of up to 6 pages, plus 1 page for references. A maximum of two extra content pages per full paper is allowed (i.e, up to 8 pages plus 1 page for references), at an additional charge per extra page as specified in the <a href="<?php echo "?ui=registration"; ?>">registration</a> page. SSCI will be using a new  <a href="<?php echo "?ui=presentation-format"; ?>">presentation format</a> for full papers this year. </li>
			    <li><b>Short papers:</b> papers of up to 4 pages, plus 1 page for references. </li>
				<li><b>Late breaking papers:</b> extended abstracts of up to 2 pages, including references, if any. </li>
				<li><b>Abstract (poster-only):</b> abstracts of up to 250 words.</li>
				<li><b>Journal to conference: </b> up to 1 page listing bullet points with the highlights of the paper, and an explanation on why you believe the paper to be relevant to SSCI. </li>
			</ul>
			</p>
			<p>For a description of each paper type, please refer to the <a href="<?php echo "?ui=call-for-papers"; ?>">call for papers</a>. </p>
			<p>
		  <h2><b>Open Science for Full and Short Papers</b> </h2>
			We encourage all authors to make their data/code available upon acceptance of full and short papers to increase reproducibility and replicability. 
			</p>
			<p>
			Please add a note in the last paragraph of the introduction of your submitted paper either stating that you will make your data/code available upon acceptance, or with a justification on why you cannot make your data/code available. Please replace this note by a link to the data/code in your camera-ready paper if you are sharing. You may use any online repository that you wish for this purpose. We suggest <a href="https://zenodo.org/" target="_blank"> Zenodo </a> as it produces a permanent link with a DOI.
