				<li> Abstract (poster-only) submissions and Journal to Conference (J2C) papers     must not have been previously presented, under consideration for presentation, or submitted for presentation at other conferences, congresses, symposia or workshop whilst under consideration for presentation at IEEE SCCI 2025.</li>
