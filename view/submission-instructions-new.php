				<ul>
					<li>The use of artificial intelligence (AI)-generated text in an article must be disclosed in the acknowledgements section of any paper submitted to an IEEE Conference or Periodical. The sections of the paper that use AI-generated text must have a citation to the AI system used to generate the text.</li>
				</ul>
				</li>
				<li>No authorship changes will be allowed after acceptance. Please ensure that you are following this guideline to avoid any issues with publication.</li>
