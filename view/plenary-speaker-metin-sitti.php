		    <h2><b>Abstract: </b> </h2>
				<p>Intelligence of physical agents is not only enabled by their computational intelligence in their brain, but also by their physical intelligence encoded in their body. This presentation reports bioinspired and abstract physical intelligence methods designed and implemented in small-scale robots from insect scale down to cell-size scale. Light-powered phototactic and bacteria-driven chemo/magnetotactic microswimmers are presented at the cell-size scale. At the milliscale, bioinspired soft-bodied robots with magneto-elastic composite bodies are presented to navigate in complex, confined spaces. Soft-body design enables active shape programming-based adaptive and multimodal navigation, diverse functions, and safe operation. These soft millirobots are aimed to be used as implantable wireless medical devices in the small-diameter, tortuous, risky and hard-to-reach blood vessels and other sites inside the human body. Liquid crystal elastomer types of stimuli-responsive materials are also integrated with magneto-elastic composites towards self-sensing and self-adapting millirobots. Finally, mechanical computing systems using bistable metastructures are proposed to encode physical computing in millimachines.
				</p>
